"""Approximate names for major paleocontinents and ocean basins, 0–750 Ma.

Intervals and marker positions are schematic. Early Paleozoic and especially
Precambrian reconstructions differ between published models.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class PaleoUnit:
    key: str
    name: str
    group: str
    older_ma: int
    younger_ma: int
    description: str
    # Present-day proxy locations that the plate model can carry through time.
    # Several points give a more useful visual reference for large units/basins.
    anchors: tuple[tuple[float, float], ...]
    marker_mode: str = "mean"

    def active(self, age: float) -> bool:
        return self.younger_ma <= age <= self.older_ma


@dataclass(frozen=True)
class AgeStory:
    older_ma: int
    younger_ma: int
    heading: str
    text: str

    def active(self, age: float) -> bool:
        return self.younger_ma <= age <= self.older_ma


